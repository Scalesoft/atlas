-- Background jobs (3.3 plan §4.1): the definitions are code, these rows their state. Job holds the pause and the next due time,
-- JobRun every run with its checkpoint, summary, error and log; it replaces the run rows of the features. Operational: JobRun ages by
-- OperationalRetention (30 days, 20 runs a job), Job is kept.
CREATE TABLE "Job" (
  "Id" text NOT NULL CONSTRAINT "PK_Job" PRIMARY KEY,
  "ModuleId" text NOT NULL,
  "Paused" boolean NOT NULL DEFAULT false,
  "PausedBy" uuid NULL,
  "PausedAt" timestamptz NULL,
  "NextDueAt" timestamptz NULL,
  "CompletedAt" timestamptz NULL
);

CREATE TABLE "JobRun" (
  "Id" bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_JobRun" PRIMARY KEY,
  "JobId" text NOT NULL,
  "Key" text NULL,
  "Trigger" text NOT NULL CONSTRAINT "CK_JobRun_Trigger" CHECK ("Trigger" IN ('startup', 'event', 'schedule', 'manual', 'retry')),
  "Reason" text NULL,
  "RequestedBy" uuid NULL,
  "SpaceId" uuid NULL,
  "State" text NOT NULL CONSTRAINT "CK_JobRun_State" CHECK ("State" IN ('queued', 'running', 'succeeded', 'failed', 'cancelled')),
  "Attempt" integer NOT NULL DEFAULT 0,
  "QueuedAt" timestamptz NOT NULL DEFAULT now(),
  "NotBefore" timestamptz NULL,
  "StartedAt" timestamptz NULL,
  "HeartbeatAt" timestamptz NULL,
  "FinishedAt" timestamptz NULL,
  "CancelRequested" boolean NOT NULL DEFAULT false,
  "Progress" jsonb NULL,
  "Summary" jsonb NULL,
  "Error" text NULL,
  "Log" jsonb NULL
);

-- Requests merge: at most one queued run per job and key; a SQL migration may insert a queued row, the runner publishes it after start.
CREATE UNIQUE INDEX "UX_JobRun_Queued" ON "JobRun" ("JobId", COALESCE("Key", '')) WHERE "State" = 'queued';
-- One run of a job at a time; the partitioned queue keeps the second waiting, the database holds the truth.
CREATE UNIQUE INDEX "UX_JobRun_Running" ON "JobRun" ("JobId") WHERE "State" = 'running';
CREATE INDEX "IX_JobRun_Job" ON "JobRun" ("JobId", "QueuedAt" DESC);
