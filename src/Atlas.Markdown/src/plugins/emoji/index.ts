// Name → character of the upstream Unicode catalog, generated by emoji.test.ts (ATLAS_UPDATE_EMOJI=1). Rendering,
// commands and Markdown need only this; the catalog itself (600 KB) is loaded by the first search.
import table from './unicode.json'

export interface EmojiPluginOptions {
  /** Explicit opt-in to upstream emoticon input rules in the rich profile. */
  enableEmoticons?: boolean
  /** Maximum results in the shared suggestion list (default 20). */
  limit?: number
  /** Extra search words keyed by upstream emoji name or shortcode. */
  aliases?: Readonly<Record<string, readonly string[]>>
}
export type MarkdownEmoji = EmojiItem & { emoji: string }

const names: Readonly<Record<string, string>> = table.names
const shortcodes: Readonly<Record<string, string>> = table.shortcodes
const emoticons: Readonly<Record<string, string>> = table.emoticons
/** The upstream lookup (`shortcodeToEmoji`): the first catalog item whose name or shortcode is `shortcode`. */
function resolve(shortcode: string): { name: string; emoji: string } | undefined {
  const name = Object.hasOwn(shortcodes, shortcode) ? shortcodes[shortcode]! : Object.hasOwn(names, shortcode) ? shortcode : undefined
  return name === undefined ? undefined : { name, emoji: names[name]! }
}

const defaultPickerShortcodes = [
  'grinning', 'smile', 'joy', 'heart_eyes', 'wink', 'thinking', 'thumbsup', 'heart', 'tada', 'fire',
  'rocket', 'white_check_mark', 'eyes', 'clap', 'pray', 'cry', 'sob', 'angry', '100', 'warning',
] as const
const defaultAliases: Readonly<Record<string, readonly string[]>> = {
  heart: ['srdce', 'láska'], grinning: ['úsměv', 'radost'], smile: ['úsměv', 'smích'],
  thumbsup: ['palec', 'souhlas'], tada: ['oslava'], rocket: ['raketa'], fire: ['oheň'], check_mark: ['hotovo'],
}
let catalog: Promise<MarkdownEmoji[]> | undefined
/** Picker entries of the upstream catalog, loaded once; a failed load is retried by the next search. */
function pickerEmojis(): Promise<MarkdownEmoji[]> {
  catalog ??= import('@tiptap/extension-emoji').then(({ emojis }) => emojis
    // Strip image URLs even if upstream's Unicode catalog gains fallbacks later.
    .filter((item): item is MarkdownEmoji => !!item.emoji).map(({ fallbackImage: _fallbackImage, ...item }) => item)
    // Unicode components only make sense inside a composed emoji. Offering them as
    // standalone picker results creates broken-looking flags, skin tones and hair.
    .filter(item => item.group !== 'components' && !item.name.startsWith('regional_indicator_')),
  error => { catalog = undefined; throw error })
  return catalog
}
const fold = (value: string) => value.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()
export async function searchEmoji(query: string, limit = 20, aliases: EmojiPluginOptions['aliases'] = {}): Promise<MarkdownEmoji[]> {
  const items = await pickerEmojis()
  const term = fold(query.replace(/^:|:$/g, ''))
  const max = Math.max(1, Math.min(100, Math.floor(limit) || 20))
  if (!term) {
    const defaults: MarkdownEmoji[] = [], seen = new Set<string>()
    for (const name of defaultPickerShortcodes) {
      const item = items.find(entry => name === entry.name || entry.shortcodes.includes(name))
      if (item && !seen.has(item.name)) { defaults.push(item); seen.add(item.name) }
    }
    return defaults.slice(0, max)
  }
  const matches = items.filter(item => [item.name, ...item.shortcodes, ...item.tags,
    ...Object.entries({ ...defaultAliases, ...aliases }).filter(([name]) => name === item.name || item.shortcodes.includes(name)).flatMap(([, words]) => words),
  ].some(word => fold(word).includes(term)))
  matches.sort((a, b) => Number(b.name === term || b.shortcodes.includes(term)) - Number(a.name === term || a.shortcodes.includes(term)))
  return matches.slice(0, max)
}
export function emojiNode(name: string): JSONContent {
  const item = resolve(name)
  if (!item) throw new TypeError(`Unknown Unicode emoji: ${name}`)
  return { type: 'emoji', attrs: { name: item.name } }
}
// Back to text, an emoji is its character: the same text a Markdown export writes.
registerMarkdownChipText('emoji', node => resolve(String(node.attrs.name))?.emoji ?? `:${node.attrs.name}:`)
const insertionMeta = 'markdownEmojiInsertion'
export const insertEmoji = defineMarkdownCommand<string>({
  id: 'emoji.insert', apply: name => ({ editor, commands, tr, dispatch }) => {
    const item = resolve(name)
    if (!item || !editor.isEditable) return false
    if (dispatch) closeMarkdownHistory(tr).setMeta(insertionMeta, true)
    return editor.schema.nodes.emoji ? commands.setEmoji(item.name) : commands.insertContent({ type: 'text', text: item.emoji })
  },
})
/** Starts the same cursor-owned picker as typing a colon. */
export const openEmojiPicker = defineMarkdownCommand<void>({
  id: 'emoji.picker', apply: () => ({ commands, editor }) => editor.isEditable && commands.insertContent({ type: 'text', text: ':' }),
})

/**
 * The upstream `emoji` node (@tiptap/extension-emoji) with the same schema, rendering and commands, built on the name table:
 * the upstream module holds its whole catalog, so extending it would load that with every document. Atlas's own choices
 * stay: no paste rules, no text-to-node normalizer, emoticon input rules only on request.
 */
function createRichEmoji(suggestion: Omit<SuggestionOptions<MarkdownEmoji>, 'editor'>, enableEmoticons: boolean) {
  return Node.create({
    name: 'emoji', inline: true, group: 'inline', selectable: false,
    addStorage() {
      return { markdown: {
        serialize(state: { write(text: string): void }, node: { attrs: { name: string } }) { state.write(resolve(node.attrs.name)?.emoji ?? `:${node.attrs.name}:`) },
      } }
    },
    addAttributes() {
      return { name: { default: null, parseHTML: element => element.dataset.name, renderHTML: attributes => ({ 'data-name': attributes.name }) } }
    },
    parseHTML() { return [{ tag: `span[data-type="${this.name}"]` }] },
    renderHTML({ HTMLAttributes, node }) {
      return ['span', mergeAttributes(HTMLAttributes, { 'data-type': this.name }), resolve(node.attrs.name)?.emoji ?? `:${node.attrs.name}:`]
    },
    renderText({ node }) { return resolve(node.attrs.name)?.emoji ?? `:${node.attrs.name}:` },
    renderMarkdown: node => node.attrs?.name ? `:${node.attrs.name}:` : '',
    addCommands() {
      return { setEmoji: shortcode => ({ chain }) => {
        const item = resolve(shortcode)
        if (!item) return false
        chain().insertContent({ type: this.name, attrs: { name: item.name } })
          .command(({ tr, state }) => { tr.setStoredMarks(state.doc.resolve(state.selection.to - 1).marks()); return true }).run()
        return true
      } }
    },
    addInputRules() {
      if (!enableEmoticons) return []
      const rules = [new InputRule({ find: /:([a-zA-Z0-9_+-]+):$/, handler: ({ range, match, chain }) => {
        const name = match[1]!
        if (!resolve(name)) return
        // An automatic chip: Backspace right after deletes the closing colon (`:name` comes back), Ctrl+Z undoes the chip and not the typing.
        chain().insertContentAt(range, { type: this.name, attrs: { name } })
          .command(({ tr, state }) => { tr.setStoredMarks(state.doc.resolve(state.selection.to - 1).marks()); markMarkdownAutoConversion(tr, { from: range.from, to: range.from + 1, text: match[0].slice(0, -1) }); return true }).run()
      } })]
      const faces = Object.keys(emoticons)
      if (faces.length) rules.push(nodeInputRule({ find: new RegExp(`(?:^|\\s)(${faces.map(face => escapeForRegEx(face)).join('|')}) $`), type: this.type,
        getAttributes: match => Object.hasOwn(emoticons, match[1]!) ? { name: emoticons[match[1]!] } : undefined }))
      return rules
    },
    addProseMirrorPlugins() {
      return [Suggestion({ editor: this.editor, ...suggestion }), new Plugin({ key: new PluginKey('emoji'), props: {
        // Firefox moves the caret into an inline leaf; step over the emoji as upstream does.
        handleKeyDown: (view, event) => {
          if (!isFirefox() || (event.key !== 'ArrowLeft' && event.key !== 'ArrowRight')) return false
          if (event.shiftKey || event.ctrlKey || event.altKey || event.metaKey) return false
          const { selection } = view.state
          if (!selection.empty || !(selection instanceof TextSelection)) return false
          const $pos = selection.$from
          const node = event.key === 'ArrowLeft' ? $pos.nodeBefore : $pos.nodeAfter
          if (!node || node.type !== this.type) return false
          const target = event.key === 'ArrowLeft' ? $pos.pos - node.nodeSize : $pos.pos + node.nodeSize
          if (event.key === 'ArrowLeft' ? target < $pos.start() : target > $pos.end()) return false
          view.dispatch(view.state.tr.setSelection(TextSelection.create(view.state.doc, target)))
          return true
        },
        handleDoubleClickOn: (_view, pos, node) => {
          if (node.type !== this.type) return false
          this.editor.commands.setTextSelection({ from: pos, to: pos + node.nodeSize })
          return true
        },
      } })]
    },
  })
}

export function createEmojiPlugin(options: EmojiPluginOptions = {}): MarkdownPlugin {
  return { id: 'emoji', apiVersion: 1, entities: [defineMarkdownEntityKind({ kind: 'emoji', inline: 'emoji' })], schemaVersion: 1, profiles: ['rich', 'markdown-safe'], create({ profile }) {
    const pluginKey = new PluginKey('markdownEmojiSuggestion')
    const suggestion: Omit<SuggestionOptions<MarkdownEmoji>, 'editor'> = {
      pluginKey, char: ':', allowedPrefixes: [' ', '\n', '('], allowSpaces: false,
      shouldShow: shouldShowMarkdownSuggestion,
      // A catalog that cannot load leaves the list empty; the next query asks again.
      items: ({ query }) => searchEmoji(query, options.limit, options.aliases).catch(() => []),
      allow: ({ editor, state, range }) => {
        const position = state.doc.resolve(range.from)
        return editor.isEditable && !position.parent.type.spec.code && !position.marks().some(mark => mark.type.name === 'code' || mark.type.name === 'link')
      },
      command: ({ editor, range, props }) => {
        if (!editor.isEditable || editor.view.composing) return
        const item = resolve(props.name)
        if (!item) return
        const node = profile === 'rich' ? editor.schema.nodes.emoji!.create({ name: item.name }) : editor.schema.text(item.emoji)
        dispatchMarkdownHistoryOperation(editor, editor.state.tr.replaceWith(range.from, range.to, node))
        editor.view.focus()
      },
      render: createMarkdownSuggestionRenderer<MarkdownEmoji>({ pluginKey, label: emojiStrings.pickerLabel, testId: 'emoji-menu', emptyText: emojiStrings.emptyResults, mapItem: item => ({ id: item.name, title: item.name.replaceAll('_', ' '), description: `:${item.shortcodes[0] ?? item.name}:`, icon: item.emoji }) }),
    }
    const safeEmoji = Extension.create({ name: 'markdownUnicodeEmoji', addProseMirrorPlugins() { return [Suggestion({ editor: this.editor, ...suggestion })] } })
    return {
      extensions: [profile === 'rich' ? createRichEmoji(suggestion, options.enableEmoticons ?? false) : safeEmoji], commands: [insertEmoji, openEmojiPicker],
      actions: { slash: [{ id: 'emoji.picker', label: emojiStrings.pickerLabel, description: emojiStrings.pickerDescription, icon: 'svg:smile', keywords: ['emoji', 'smajlík', 'smajlik'], command: openEmojiPicker() }] },
      markdownLossy(document) { let found = false; document.descendants(node => { found ||= node.type.name === 'emoji' }); return found },
      // Ctrl+Space on a written shortcode („:smile“ or „:smile:“): that emoji in its place, one undo step.
      intentions: ({ editor, from, to, text }) => {
        const name = /^:([a-zA-Z0-9_+-]+):?$/u.exec(text)?.[1], item = name ? resolve(name) : undefined
        if (!item) return []
        return [{ id: 'emoji.from-text', label: emojiStrings.fromText(item.emoji, item.name.replaceAll('_', ' ')), icon: item.emoji, keywords: ['emoji'], run: () => {
          if (!editor.isEditable || editor.state.doc.textBetween(from, to) !== text) return
          const node = profile === 'rich' ? editor.schema.nodes.emoji!.create({ name: item.name }) : editor.schema.text(item.emoji)
          dispatchMarkdownHistoryOperation(editor, editor.state.tr.replaceWith(from, to, node))
        } }]
      },
      onCreate({ editor }) {
        const close = ({ transaction }: { transaction: Transaction }) => {
          if (transaction.getMeta(insertionMeta) && !editor.isDestroyed) editor.view.dispatch(closeMarkdownHistory(editor.state.tr).setMeta('addToHistory', false))
        }
        editor.on('transaction', close)
        return () => { editor.off('transaction', close) }
      },
    }
  } }
}
