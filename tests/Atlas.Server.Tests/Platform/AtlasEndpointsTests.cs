    /// <summary>
    /// MapAtlasEndpoints is the one place a feature can be forgotten, and a forgotten Map* is a silent
    /// 404 for a whole feature. The pinned set tracks the supported feature routes; builtin
    /// authentication is enabled here, so /api/auth/login and /api/auth/activate are part of it, and the site runs in
    /// Development, so the developer sign-in /api/auth/developer is too (never mapped elsewhere). The four
    /// routes MapOpenIdConnect adds only when a provider is configured (/api/auth/oidc/{id}/login,
    /// /api/profile/identities, /api/profile/identities/{id}/link, /signin-oidc/{id}) are deliberately not
    /// in the set: this site has no provider, so OidcEndpoints returns after /api/auth/methods.
    /// EndpointDataSource resolves as a single service in this framework version.
    /// </summary>
    [Trait("Category", "Smoke")]
    [PostgreSqlFact]
    public async Task Every_supported_feature_route_is_registered()
    {
        // Every optional module on, so the set pins their routes too; BoardsModuleProfileTests shows them gone when off.
        await using var site = await AtlasHttpSite.CreateAsync("atlas_routes_", settings =>
        {
            foreach (var (key, value) in TestModules.AllEnabledSettings)
            {
                settings[key] = value;
            }
        });
        using var client = site.Client();
        // Force the pipeline (and therefore the endpoint data sources) to be built.
        await client.GetAsync("/health/live");
        var actual = site.Services.GetRequiredService<EndpointDataSource>().Endpoints
            .OfType<RouteEndpoint>()
            .Select(endpoint => Methods(endpoint) + " " + endpoint.RoutePattern.RawText)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(route => route, StringComparer.Ordinal)
            .ToArray();
        Assert.True(Expected.Order(StringComparer.Ordinal).SequenceEqual(actual),
            $"Missing routes: {string.Join(", ", Expected.Except(actual))}\nUnexpected routes: {string.Join(", ", actual.Except(Expected))}");
    }

    /// <summary>Verbs joined by a comma; a route without a verb constraint (health checks, SPA fallback) is ANY.</summary>
    private static string Methods(RouteEndpoint endpoint)
    {
        return endpoint.Metadata.GetMetadata<IHttpMethodMetadata>() is { HttpMethods: { Count: > 0 } methods }
            ? string.Join(",", methods.OrderBy(method => method, StringComparer.Ordinal))
            : "ANY";
    }

