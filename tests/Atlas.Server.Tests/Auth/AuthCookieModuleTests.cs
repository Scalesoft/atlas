using System.Text.Json.Nodes;
using Microsoft.AspNetCore.Authentication;
using Microsoft.AspNetCore.Authentication.Cookies;
using Microsoft.AspNetCore.Http;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.FileProviders;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Options;
using Atlas.Server.Features.Auth;
using Xunit;

namespace Atlas.Server.Tests.Auth;

public sealed class AuthCookieModuleTests
{
    /// <summary>
    /// The access-denied event is unreachable while every group is a bare RequireAuthorization(),
    /// which only challenges. Wave 4's policy-bearing groups make it live, so its body is asserted
    /// here directly rather than left to the first feature that trips over it.
    /// </summary>
    [Theory]
    [InlineData("/api/spaces", 403, "Přístup byl odepřen.")]
    [InlineData("/settings/spaces", 403, null)]
    public async Task Access_denied_writes_the_problem_body_for_the_API_and_a_bare_status_for_a_page(string path, int status, string? title)
    {
        using var keyring = new CookieServices();
        var context = new DefaultHttpContext { Request = { Path = path }, RequestServices = keyring.Provider };
        var body = new MemoryStream();
        context.Response.Body = body;

        await keyring.Events.OnRedirectToAccessDenied(Redirect(context));

        Assert.Equal(status, context.Response.StatusCode);
        Assert.Equal(title, Title(body));
    }

    [Theory]
    [InlineData("/api/auth/me", 401, "Přihlaste se.")]
    [InlineData("/space/engineering", 401, null)]
    public async Task Challenge_writes_the_problem_body_for_the_API_and_a_bare_status_for_a_page(string path, int status, string? title)
    {
        using var keyring = new CookieServices();
        var context = new DefaultHttpContext { Request = { Path = path }, RequestServices = keyring.Provider };
        var body = new MemoryStream();
        context.Response.Body = body;

        await keyring.Events.OnRedirectToLogin(Redirect(context));

        Assert.Equal(status, context.Response.StatusCode);
        Assert.Equal(title, Title(body));
    }

    private static RedirectContext<CookieAuthenticationOptions> Redirect(HttpContext context)
    {
        var scheme = new AuthenticationScheme(CookieAuthenticationDefaults.AuthenticationScheme, null, typeof(CookieAuthenticationHandler));
        return new RedirectContext<CookieAuthenticationOptions>(context, scheme, new CookieAuthenticationOptions(), new AuthenticationProperties(), "/login");
    }

    private static string? Title(MemoryStream body)
    {
        if (body.Length == 0)
        {
            return null;
        }
        return JsonNode.Parse(body.ToArray())!["title"]!.GetValue<string>();
    }

    /// <summary>Real cookie options from AddAuthCookies, plus the data protection directory it may create.</summary>
    private sealed class CookieServices : IDisposable
    {
        private readonly string m_keysPath = Path.Combine(Path.GetTempPath(), "atlas-cookie-test-" + Guid.NewGuid().ToString("N"));
        private readonly ServiceProvider m_provider;

        public CookieServices()
        {
            var configuration = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string, string?>
            {
                ["DataProtection:KeysPath"] = m_keysPath
            }).Build();
            var services = new ServiceCollection();
            services.AddSingleton<IConfiguration>(configuration);
            services.AddLogging();
            services.AddAuthCookies(configuration, new CookieEnvironment());
            services.AddProblemDetails();
            m_provider = services.BuildServiceProvider();
            Events = m_provider.GetRequiredService<IOptionsMonitor<CookieAuthenticationOptions>>()
                .Get(CookieAuthenticationDefaults.AuthenticationScheme).Events;
        }

        public IServiceProvider Provider => m_provider;

        public CookieAuthenticationEvents Events { get; }

        public void Dispose()
        {
            m_provider.Dispose();
            // This directory is generated by this fixture under the OS temp folder only.
            var resolved = Path.GetFullPath(m_keysPath);
            if (!resolved.StartsWith(Path.GetFullPath(Path.GetTempPath()), StringComparison.OrdinalIgnoreCase)
                || !Path.GetFileName(resolved).StartsWith("atlas-cookie-test-", StringComparison.Ordinal))
            {
                throw new InvalidOperationException("Unexpected test directory.");
            }
            if (Directory.Exists(resolved))
            {
                Directory.Delete(resolved, true);
            }
        }

        private sealed class CookieEnvironment : IHostEnvironment
        {
            public string EnvironmentName { get; set; } = Environments.Development;
            public string ApplicationName { get; set; } = "CookieTests";
            public string ContentRootPath { get; set; } = Path.GetTempPath();
            public IFileProvider ContentRootFileProvider { get; set; } = new NullFileProvider();
        }
    }
}
